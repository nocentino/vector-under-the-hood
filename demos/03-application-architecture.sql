/* -----------------------------------------------------------------------------
   1b. The chunk column — why it matters
   -----------------------------------------------------------------------------
   QuestionEmbeddings.chunk stores the EXACT text that was embedded. This is
   subtle but important:

     DECOUPLING FROM SOURCE
       The source row (Posts.Title, Posts.Tags) can change. The chunk column
       records what the vector actually represents at the time it was generated.
       If the title changes, the chunk tells you the embedding is stale.

     CONTEXT FOR THE APPLICATION
       At retrieval time, the Python app can return chunk text directly as RAG
       context without re-joining to Posts. One query, one round trip.

     AUDIT TRAIL
       "This is the exact text the vector represents." Useful for debugging
       retrieval quality when results look wrong.

   In a production chunking pipeline, chunk would contain a sliding window of
   document text (e.g., 512 tokens with 64-token overlap). Here it is the
   question title concatenated with the cleaned tag string.
----------------------------------------------------------------------------- */
