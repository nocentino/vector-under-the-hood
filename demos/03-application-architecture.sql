/* =============================================================================
   SECTION 1 — SCHEMA DESIGN: WHY A SEPARATE EMBEDDINGS TABLE
   ============================================================================= */

/* -----------------------------------------------------------------------------
   1a. The separation pattern
   -----------------------------------------------------------------------------
   QuestionEmbeddings is a SATELLITE TABLE to Posts — related by PostId,
   stored on a separate filegroup, containing only the data the vector
   pipeline needs.

   Why not just add an embeddings column directly to Posts?

     LIFECYCLE MISMATCH
       Posts are written by users. Embeddings are generated by a background
       pipeline. A single table mixes two completely different write patterns.
       Adding an embedding column to Posts means every embedding update
       generates a log record on the operational table.

     REBUILD INDEPENDENCE
       When you change models (e.g., upgrade from nomic-embed-text 768-dim to
       mxbai-embed-large 1024-dim), you TRUNCATE and rebuild QuestionEmbeddings
       without touching Posts. The PostId foreign key keeps them aligned.

     PARTIAL COVERAGE
       Not every Post needs an embedding. We embedded the top 10,000
       questions by Score. The satellite table naturally represents this
       partial coverage: a missing row means "not yet embedded," not NULL data.

     STORAGE TIERING
       The EMBEDDINGS filegroup can live on different storage than PRIMARY.
       Vector I/O (large sequential reads during index build, random reads
       during graph traversal) shouldn't share bandwidth with OLTP I/O.

   For your own systems: this is the production-ready pattern. Keep the
   vector column and its index in a satellite table that can be fully rebuilt
   without touching the transactional source of truth.
----------------------------------------------------------------------------- */

-- Embedding coverage — how much of the dataset is vectorized?
SELECT
    total.total_questions,
    embedded.embedded_questions,
    CAST(embedded.embedded_questions AS FLOAT) / total.total_questions * 100
        AS pct_embedded
FROM (SELECT COUNT(*) AS total_questions     FROM dbo.Posts              WHERE PostTypeId = 1) total
CROSS JOIN
     (SELECT COUNT(*) AS embedded_questions  FROM dbo.QuestionEmbeddings)                     embedded;
GO

